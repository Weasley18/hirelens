"""Build EVALUATION.md (repository root) from the recorded runs in eval/history/.

    python -m eval.dashboard            # rewrite EVALUATION.md
    python -m eval.dashboard --check    # exit 1 if EVALUATION.md is out of date (CI)

Runs are recorded by `python -m eval.run_eval ... --record`; the evaluation workflow records a
full run on demand and commits the history together with this page. GitHub renders the charts.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HISTORY = Path(__file__).parent / "history"
FAIRNESS = Path(__file__).parent / "fairness" / "latest.json"
OUTPUT = Path(__file__).resolve().parents[3] / "EVALUATION.md"


def load_history() -> list[dict]:
    runs = [json.loads(p.read_text()) for p in sorted(HISTORY.glob("*.json"))]
    return sorted(runs, key=lambda r: r["timestamp"])


def _get(run: dict, *path):
    value = run
    for key in path:
        value = (value or {}).get(key) if isinstance(value, dict) else None
    return value


def _pct(value) -> str:
    return "—" if value is None else f"{value:.0%}"


def _num(value, fmt: str) -> str:
    return "—" if value is None else format(value, fmt)


def _secs(value) -> str:
    return "—" if value is None else f"{value:.1f}s"


def _max_gap(run: dict):
    return max((_get(run, "fairness", "spreads") or {}).values(), default=None)


def _chart(title: str, labels: list[str], series: dict[str, list], y_label: str, y_max: float | None = None) -> list[str]:
    """A Mermaid xychart. Missing values are left out of the chart (a series needs every point)."""
    complete = {name: values for name, values in series.items() if values and all(v is not None for v in values)}
    if len(labels) < 2 or not complete:
        return []
    top = y_max if y_max is not None else max(max(v) for v in complete.values()) * 1.2 or 1
    lines = ["```mermaid", "xychart-beta", f'    title "{title}"',
             "    x-axis [" + ", ".join(f'"{label}"' for label in labels) + "]",
             f'    y-axis "{y_label}" 0 --> {top:g}']
    lines += [f"    line [{', '.join(f'{v:g}' for v in values)}]" for values in complete.values()]
    lines.append("```")
    if len(complete) > 1:
        lines.append("Lines, in order: " + ", ".join(complete) + ".")
    return lines + [""]


def render(runs: list[dict], fairness: dict | None = None) -> str:
    out = ["# Evaluation", "",
           "Generated by `python -m eval.dashboard` from `apps/ml-service/eval/history/`; do not edit by hand.",
           "Each run puts the hand-written edge cases in `apps/ml-service/eval/manual_pairs.json` through the",
           "full inference path (retrieval, the hosted model, schema validation, quote verification). Pull",
           "requests that change the prompt, model code or schema run the `ci` subset as a gate; full runs",
           "are recorded on demand from the Evaluation workflow.", ""]
    full = [r for r in runs if r.get("subset") == "all"]
    if full:
        latest = full[-1]
        out += ["## Latest full run", "",
                f"{latest['timestamp'][:10]} · model `{latest.get('model')}` · {latest['analyses']} analyses "
                f"({latest['cases']} cases × {latest['repeat']})", "",
                "| Metric | Value |", "|---|---|",
                f"| Cases passing every automated check | {latest['passed']}/{latest['cases']} ({_pct(latest['passRate'])}) |",
                f"| Claims backed by a quote from the documents | {_pct(_get(latest, 'citations', 'supportRate'))} |",
                f"| Latency p50 / p95 | {_secs(_get(latest, 'latencySeconds', 'p50'))} / "
                f"{_secs(_get(latest, 'latencySeconds', 'p95'))} |",
                f"| Cost per analysis | {'—' if _get(latest, 'costUsd', 'perAnalysis') is None else '$' + format(_get(latest, 'costUsd', 'perAnalysis'), '.5f')} |",
                f"| Score spread across repeats (mean / max) | {_num(_get(latest, 'scoreSpread', 'mean'), '.1f')} / "
                f"{_num(_get(latest, 'scoreSpread', 'max'), 'd')} points |",
                f"| Largest counterfactual gap (name, age, career break) | {_num(_max_gap(latest), '.1f')} points |", ""]
        if latest.get("flagged"):
            out += ["Flagged in this run:", ""]
            out += [f"- `{case['id']}`: {'; '.join(map(str, case['problems']))}" for case in latest["flagged"]]
            out.append("")
        if latest.get("note"):
            out += [f"_{latest['note']}_", ""]

    labels = [r["timestamp"][5:10] for r in full]
    charts = _chart("Full runs: quality (%)", labels, {
        "cases passing": [None if r.get("passRate") is None else round(r["passRate"] * 100, 1) for r in full],
        "claims backed by a quote": [None if _get(r, "citations", "supportRate") is None
                                     else round(_get(r, "citations", "supportRate") * 100, 1) for r in full],
    }, "%", 100)
    charts += _chart("Full runs: p95 latency (s)", labels,
                     {"p95": [_get(r, "latencySeconds", "p95") for r in full]}, "seconds")
    charts += _chart("Full runs: cost per analysis (US cents)", labels,
                     {"cost": [None if _get(r, "costUsd", "perAnalysis") is None
                               else round(_get(r, "costUsd", "perAnalysis") * 100, 3) for r in full]}, "cents")
    if charts:
        out += ["## Over time", "", *charts]

    out += ["## Every recorded run", "",
            "| Date | Commit | Cases | Model | Passing | Quoted claims | p50 | p95 | Cost/analysis | Max counterfactual gap |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for r in reversed(runs):
        cost = _get(r, "costUsd", "perAnalysis")
        out.append(f"| {r['timestamp'][:10]} | {('`' + r['commit'][:7] + '`') if r.get('commit') else '—'} | "
                   f"{r.get('subset')} ×{r.get('repeat')} | {r.get('model') or '—'} | {r['passed']}/{r['cases']} | "
                   f"{_pct(_get(r, 'citations', 'supportRate'))} | {_secs(_get(r, 'latencySeconds', 'p50'))} | "
                   f"{_secs(_get(r, 'latencySeconds', 'p95'))} | "
                   f"{'—' if cost is None else '$' + format(cost, '.5f')} | {_num(_max_gap(r), '.1f')} |")
    out.append("")

    if fairness:
        out += ["## Fairness audit", "",
                f"Latest audit {fairness['timestamp'][:10]}, model `{fairness.get('model')}`: "
                f"{fairness['variants']} counterfactual variants of {fairness['bases']} resume/JD pairs. "
                "Full method and results: [FAIRNESS.md](FAIRNESS.md).", "",
                "| Attribute | Largest mean difference | p-value (permutation) | Verdict |", "|---|---|---|---|"]
        for attribute in fairness["attributes"]:
            out.append(f"| {attribute['name']} | {attribute['maxMeanDifference']:.2f} points | "
                       f"{attribute['pValue']:.3f} | {attribute['verdict']} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if EVALUATION.md is out of date")
    args = parser.parse_args(argv)
    fairness = json.loads(FAIRNESS.read_text()) if FAIRNESS.exists() else None
    page = render(load_history(), fairness)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != page:
            raise SystemExit("EVALUATION.md is out of date: run python -m eval.dashboard")
        return
    OUTPUT.write_text(page)
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
